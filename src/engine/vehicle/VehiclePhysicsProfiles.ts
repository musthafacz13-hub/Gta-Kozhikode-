import type { VehicleAudioKind } from '../audio/AudioTypes.ts';
import {
  VEHICLE_BLUEPRINT_META,
  type VehicleFleetCategory,
  type VehicleModelId,
} from '../world/VehicleVisualFactory.ts';

export interface VehiclePhysicsProfile {
  modelId: VehicleModelId;
  displayName: string;
  category: VehicleFleetCategory;
  audioKind: VehicleAudioKind;
  length: number;
  width: number;
  height: number;
  wheelRadius: number;

  // Longitudinal & Braking Performance
  maxForwardSpeedMps: number;
  maxReverseSpeedMps: number;
  accelerationMps2: number;
  reverseAccelMps2: number;
  brakeForceMps2: number;
  handbrakeForceMps2: number;
  coastingDrag: number;
  rollingResistance: number;

  // Mass, Geometry & Turning Dynamics
  massKg: number;
  wheelbaseMeters: number;
  minTurnRadiusMeters: number;
  maxSteerAngleRad: number;
  steeringResponseRate: number;
  steeringReturnRate: number;
  highSpeedSteerDamping: number;

  // Tires, Surface & Chassis Suspension
  tireGrip: number;
  handbrakeSlipFactor: number;
  offroadSpeedFactor: number;
  offroadDragFactor: number;
  centerOfGravityY: number;
  suspensionPitchFactor: number;
  suspensionRollFactor: number;
  maxLeanAngleRad: number;

  // Entry / Seating / Driver Geometry
  isEnclosed: boolean;
  driverDoorLocalX: number;
  driverDoorLocalZ: number;
  driverSeatOffset: { x: number; y: number; z: number };
  riderLeanForwardRad: number;
}

function buildProfile(
  modelId: VehicleModelId,
  overrides: Omit<
    VehiclePhysicsProfile,
    'modelId' | 'displayName' | 'category' | 'audioKind' | 'length' | 'width' | 'height' | 'wheelRadius'
  >,
): VehiclePhysicsProfile {
  const meta = VEHICLE_BLUEPRINT_META[modelId];
  return {
    modelId,
    displayName: meta.displayName,
    category: meta.category,
    audioKind: meta.audioKind,
    length: meta.length,
    width: meta.width,
    height: meta.height,
    wheelRadius: meta.wheelRadius,
    ...overrides,
  };
}

