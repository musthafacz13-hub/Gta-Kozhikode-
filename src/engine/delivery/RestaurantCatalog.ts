export function isRestaurantOpenAtHour(restaurant: RestaurantSpec, hour: number): boolean {
  const normalized = ((Math.floor(hour) % 24) + 24) % 24;
  if (restaurant.closeHour >= 24) {
    return normalized >= restaurant.openHour;
  }
  if (restaurant.openHour <= restaurant.closeHour) {
    return normalized >= restaurant.openHour && normalized < restaurant.closeHour;
  }
  return normalized >= restaurant.openHour || normalized < restaurant.closeHour;
}

export function getRestaurantById(id: string): RestaurantSpec | null {
  return KOZHIKODE_RESTAURANTS.find((r) => r.id === id) ?? null;
}

export function getCustomerLocationById(id: string): CustomerLocationSpec | null {
  return CUSTOMER_DELIVERY_LOCATIONS.find((c) => c.id === id) ?? null;
}

export function findRestaurantNearPoint(
  x: number,
  z: number,
  maxDistanceMeters = 10,
): { restaurant: RestaurantSpec; distanceMeters: number } | null {
  let best: RestaurantSpec | null = null;
  let bestDist = maxDistanceMeters;
  for (let i = 0; i < KOZHIKODE_RESTAURANTS.length; i++) {
    const r = KOZHIKODE_RESTAURANTS[i];
    const d = Math.hypot(x - r.pickupX, z - r.pickupZ);
    if (d <= bestDist) {
      bestDist = d;
      best = r;
    }
  }
  return best ? { restaurant: best, distanceMeters: Number(bestDist.toFixed(1)) } : null;
}
